async function main() {
  const me = await loadMe();
  const a = me.access || {};
  const admin = !!me.user.isAdmin;
  const ok = (cond) => !cond || cond(a, admin);
  const visible = SECTIONS
    .filter(([, , cond]) => ok(cond))
    .map(([id, title, , items]) => [id, title, items.filter(([, , cond]) => ok(cond))])
    .filter(([, , items]) => items.length);
  const app = document.getElementById('app');
  clear(app,
    portalTopbar(me, 'help'),
    h('div.layout', h('main.main.full', h('div.page.help-page',
      h('div.breadcrumbs', h('a', { href: '/' }, 'ИТ-портал'), h('span.sep', '/'), h('span', 'Справка')),
      h('div.page-head', h('h1', 'Справка')),
      h('p.muted', 'Коротко о том, где что находится, — по разделам, доступным вам. Подробные пояснения есть и на самих страницах — серым текстом под настройками.'),
      h('div.help-toc', visible.map(([id, title]) => h('a', { href: '#' + id }, title))),
      visible.map(([id, title, items]) => h('section.panel', { id },
        h('h2', title),
        h('dl.help-list', items.map(([k, v]) => [h('dt', k), h('dd', v)]))))))));
  if (location.hash) document.getElementById(location.hash.slice(1))?.scrollIntoView();
}

main().catch((e) => { document.getElementById('app').textContent = 'Ошибка загрузки: ' + e.message; });
