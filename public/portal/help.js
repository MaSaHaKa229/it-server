const norm = (s) => String(s).toLowerCase().replace(/ё/g, 'е');
const stepText = (s) => (Array.isArray(s) ? s[0] : s);

async function main() {
  const me = await loadMe();
  const a = me.access || {};
  const admin = !!me.user.isAdmin;
  const ok = (cond) => !cond || cond(a, admin);
  const keep = (list) => (list || []).filter((s) => !Array.isArray(s) || ok(s[1])).map(stepText);

  // Только доступное пользователю: разделы → подразделы → шаги и советы
  const tree = SECTIONS.filter((s) => ok(s.cond)).map((s) => ({
    ...s,
    subs: s.subs.filter((x) => ok(x.cond)).map((x) => ({ ...x, steps: keep(x.steps), tips: keep(x.tips) }))
      .filter((x) => x.text || x.steps.length),
  })).filter((s) => s.subs.length);
  const flat = tree.flatMap((s) => s.subs.map((x) => ({ sec: s, sub: x, hay: norm([s.title, x.title, x.text || '', ...x.steps, ...x.tips].join(' ')) })));

  const app = document.getElementById('app');
  const nav = h('nav.hp-nav');
  const body = h('article.hp-body');
  const q = h('input.hp-q', { type: 'search', placeholder: 'Поиск по инструкции', oninput: () => drawNav() });

  function current() {
    const [sid, xid] = decodeURIComponent(location.hash.slice(1)).split('/');
    const sec = tree.find((s) => s.id === sid) || tree[0];
    const sub = sec.subs.find((x) => x.id === xid) || sec.subs[0];
    return { sec, sub };
  }

  function drawNav() {
    const { sec, sub } = current();
    const term = norm(q.value.trim());
    if (term) {
      const found = flat.filter((f) => term.split(/\s+/).every((w) => f.hay.includes(w)));
      clear(nav, found.length
        ? found.map((f) => h('a.hp-sub', { href: `#${f.sec.id}/${f.sub.id}` }, h('small.muted', f.sec.title + ' · '), f.sub.title))
        : h('p.muted.small', 'Ничего не найдено'));
      return;
    }
    clear(nav, tree.map((s) => h('div.hp-sec' + (s === sec ? '.open' : ''),
      h('a.hp-sec-title', { href: `#${s.id}` }, h('span.hp-ico', s.icon), s.title),
      s === sec ? s.subs.map((x) => h('a.hp-sub' + (x === sub ? '.active' : ''), { href: `#${s.id}/${x.id}` }, x.title)) : null)));
  }

  function drawBody() {
    const { sec, sub } = current();
    const i = flat.findIndex((f) => f.sub === sub);
    const prev = flat[i - 1];
    const next = flat[i + 1];
    clear(body,
      h('div.breadcrumbs', h('a', { href: '#' + sec.id }, sec.title), h('span.sep', '/'), h('span', sub.title)),
      h('div.hp-head', h('h1', sub.title), sec.open ? h('a.btn', { href: sec.open }, 'Открыть раздел →') : null),
      sub.text ? h('p.hp-text', sub.text) : null,
      sub.steps.length ? h('ol.hp-steps', sub.steps.map((s) => h('li', s))) : null,
      sub.tips.length ? h('div.hp-tips', h('b', 'Полезно знать'), h('ul', sub.tips.map((t) => h('li', t)))) : null,
      sec.subs.length > 1 && sub === sec.subs[0]
        ? h('div.hp-in', h('b', 'В этом разделе:'), h('ul', sec.subs.slice(1).map((x) => h('li', h('a', { href: `#${sec.id}/${x.id}` }, x.title)))))
        : null,
      h('div.hp-pager',
        prev ? h('a', { href: `#${prev.sec.id}/${prev.sub.id}` }, '← ' + prev.sub.title) : h('span'),
        next ? h('a', { href: `#${next.sec.id}/${next.sub.id}` }, next.sub.title + ' →') : h('span')));
    document.title = `${sub.title} — Инструкция — ИТ-портал`;
    window.scrollTo(0, 0);
  }

  clear(app,
    portalTopbar(me, 'help'),
    h('div.layout', h('main.main.full', h('div.page.hp-page',
      h('div.page-head', h('div',
        h('h1', 'Инструкция'),
        h('div.muted', { style: { marginTop: '4px' } }, 'Показаны только разделы и возможности, доступные вам.'))),
      h('div.hp-grid', h('aside.hp-side', q, nav), body)))));
  const draw = () => { drawNav(); drawBody(); };
  window.addEventListener('hashchange', draw);
  draw();
}

main().catch((e) => { document.getElementById('app').textContent = 'Ошибка загрузки: ' + e.message; });
